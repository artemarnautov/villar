// Builds api/_refs.js — the server-only map catalog item id → product reference photo URLs that api/photo.js
// sends to the image model next to the 3D frame (so the photo shows the real fabric, wood and hardware).
// Owner: photo. Source: research/homecentre-raw.json (supplier listing data, never deployed under site/).
//   node tools/build-photo-refs.mjs            (writes api/_refs.js)
//   node tools/build-photo-refs.mjs --check    (exit 1 if api/_refs.js is stale)
//   node tools/build-photo-refs.mjs --width 1024   (ask the image CDN for 1024-px renditions; default: as listed)
//
// The URLs and the supplier never reach the browser: api/ is not served, api/photo.js never echoes them, and
// tools/check-public.mjs guards site/. Run before every deploy that changes site/data/catalog.json.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const raw = JSON.parse(readFileSync(resolve(ROOT, 'research/homecentre-raw.json'), 'utf8'));
const catalog = JSON.parse(readFileSync(resolve(ROOT, 'site/data/catalog.json'), 'utf8'));
const argv = process.argv.slice(2);
const widthArg = argv.includes('--width') ? Number(argv[argv.indexOf('--width') + 1]) : 0;
const MAX_PER_ITEM = 2;                       // the main component, plus one more for sets (e.g. a chair of a dining set)
const HOSTS = /^https:\/\/(media\.homecentre\.com|cdn\.media\.amplience\.net)\//;

const byPid = new Map((raw.products || []).map((p) => [String(p.pid), p]));
const compsOf = new Map((raw.catalogItems || []).map((c) => [c.id, c.components || []]));

const withWidth = (u) => {
  if (!widthArg) return u;
  const url = new URL(u);
  url.searchParams.set('w', String(widthArg));
  return url.toString();
};

const refs = {};
const missing = [];
for (const it of catalog.items || []) {
  const comps = [...(compsOf.get(it.id) || [])].sort((a, b) => (b.regular || 0) * (b.qty || 1) - (a.regular || 0) * (a.qty || 1));
  const urls = [];
  for (const c of comps) {
    const p = byPid.get(String(c.pid));
    const u = p?.image;
    if (typeof u === 'string' && HOSTS.test(u) && !urls.includes(u)) urls.push(withWidth(u));
    if (urls.length >= MAX_PER_ITEM) break;
  }
  if (urls.length) refs[it.id] = urls; else missing.push(it.id);
}

const ids = Object.keys(refs).sort();
const sorted = Object.fromEntries(ids.map((k) => [k, refs[k]]));
const hash = createHash('sha256').update(JSON.stringify(sorted)).digest('hex').slice(0, 12);
const out = resolve(ROOT, 'api/_refs.js');
const body = `// GENERATED by tools/build-photo-refs.mjs — do not edit. Server-only: never serve or echo these URLs.\n// hash ${hash}\nexport default ${JSON.stringify({ hash, refs: sorted })};\n`;

if (argv.includes('--check')) {
  const cur = existsSync(out) ? readFileSync(out, 'utf8') : '';
  const m = cur.match(/\/\/ hash (\w+)/);
  if (!m || m[1] !== hash) { console.error(`api/_refs.js is stale (have ${m?.[1] || 'none'}, want ${hash}). Run: node tools/build-photo-refs.mjs`); process.exit(1); }
  console.log(`api/_refs.js up to date (${hash})`);
} else {
  writeFileSync(out, body);
  console.log(`wrote api/_refs.js — ${ids.length}/${(catalog.items || []).length} items with reference photos, ${ids.reduce((a, k) => a + refs[k].length, 0)} URLs, ${(body.length / 1024).toFixed(1)} KB, hash ${hash}${missing.length ? `; no photo: ${missing.join(', ')}` : ''}`);
}
