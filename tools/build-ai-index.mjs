// Builds api/_catalog.js — the compact catalog/pack/layout index the assistant function reads at cold start.
// Owner: assistant. Run before every deploy that changes site/data/*:
//   node tools/build-ai-index.mjs            (writes api/_catalog.js)
//   node tools/build-ai-index.mjs --check    (exit 1 if api/_catalog.js is stale)
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildAiIndex } from '../site/js/ai/core.js';
import { withoutEditions } from '../site/js/core/data.js'; // editions flag (ART §5)

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const DATA = resolve(ROOT, 'site/data');
const read = (f) => JSON.parse(readFileSync(resolve(DATA, f), 'utf8'));

let styles;
try { styles = read('styles.json'); } catch { styles = { default: 'dark-walnut', packs: [{ id: 'dark-walnut' }] }; }
const packs = {};
for (const p of styles.packs || []) {
  const file = p.file || `stylepack-${p.id}.json`;
  try { const pk = read(file); packs[pk.id || p.id] = pk; } catch (e) { console.warn(`skip ${file}: ${e.message}`); }
}
const layout = read('layout-studio.json');
const catalog = read('catalog.json');
let budget = null;
try { budget = read('budget.json'); } catch { /* optional: no budget planning without it */ }
// editions flag: with `editions: false` in styles.json the server index offers no Villar Edition either
const index = buildAiIndex({ catalog, layout, packs: styles.editions === false ? withoutEditions(packs, catalog) : packs, styles, budget });

// Public-safety guard: nothing supplier-ish may reach the function bundle either.
const text = JSON.stringify(index);
if (/home\s*cent|https?:\/\/|\bsku\b/i.test(text)) { console.error('index contains supplier/URL/SKU data — refusing to write'); process.exit(2); }

const out = resolve(ROOT, 'api/_catalog.js');
const body = `// GENERATED by tools/build-ai-index.mjs — do not edit. Source: site/data/*.json\n// hash ${index.hash}\nexport default ${JSON.stringify(index)};\n`;
if (process.argv.includes('--check')) {
  const cur = existsSync(out) ? readFileSync(out, 'utf8') : '';
  const m = cur.match(/\/\/ hash (\w+)/);
  if (!m || m[1] !== index.hash) { console.error(`api/_catalog.js is stale (have ${m?.[1] || 'none'}, want ${index.hash}). Run: node tools/build-ai-index.mjs`); process.exit(1); }
  console.log(`api/_catalog.js up to date (${index.hash})`);
} else {
  writeFileSync(out, body);
  console.log(`wrote api/_catalog.js — ${Object.keys(index.packs).length} pack(s), ${index.catalog.items.length} items, ${index.layout.slots.length} slots, ${(body.length / 1024).toFixed(1)} KB, hash ${index.hash}`);
}
